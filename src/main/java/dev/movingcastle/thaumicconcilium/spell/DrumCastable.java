package dev.movingcastle.thaumicconcilium.spell;

import com.leclowndu93150.thaumaturge.api.spell.Spell;
import com.leclowndu93150.thaumaturge.api.spell.SpellNode;
import com.leclowndu93150.thaumaturge.api.spell.Spells;
import com.leclowndu93150.thaumaturge.api.spell.part.SpellPart;
import com.leclowndu93150.thaumaturge.api.spell.part.SpellPartKind;
import dev.movingcastle.thaumicconcilium.ThaumicConcilium;
import net.minecraft.core.Holder;
import net.minecraft.core.RegistryAccess;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.ItemStack;

/**
 * The drum stance (a bracelet in the main hand, a drum in the off hand) refuses spells that need aiming: you cannot aim
 * while drumming (decided with the user 2026-11-21). The gate is how the spell is delivered, not which effects it has.
 * <p>
 * Walking down from the spell's origin, past modifiers and flows, each branch reaches its <b>first-order delivery</b>:
 * <ul>
 *   <li>a delivery part tagged {@link #TAG} ({@code thaumicconcilium:drum_castable}: acts on an area centred on the
 *   caster, or on the caster), after which everything beneath it is fine, the area chose the targets;</li>
 *   <li>an effect with no delivery before it, which acts on the cast's origin target, the caster, as the area's centre
 *   (an effect-only spell such as Wrath Attraction, Taint Animation or Thaumaturge's burst);</li>
 *   <li>any other delivery (projectile, ray, touch, chain, spray, wall...) refuses the spell, even if an area part comes
 *   later in the chain.</li>
 * </ul>
 * Whatever the delivery, an effect tagged {@link #AIMED_EFFECTS} ({@code thaumicconcilium:drum_aimed_effects}: it reads the
 * caster's look direction itself) refuses the spell. Both tags are generated by {@code tools/gen_phase6b_data.py}.
 */
public final class DrumCastable {
    public static final TagKey<SpellPart> TAG = TagKey.create(SpellPart.REGISTRY_KEY, ThaumicConcilium.id("drum_castable"));
    public static final TagKey<SpellPart> AIMED_EFFECTS = TagKey.create(SpellPart.REGISTRY_KEY, ThaumicConcilium.id("drum_aimed_effects"));

    private DrumCastable() {
    }

    public static boolean isCastable(ItemStack focus, RegistryAccess registries) {
        Spell spell = Spells.spellOf(focus);
        if (spell == null || spell.root().children().isEmpty()) {
            return false;
        }
        var parts = registries.registryOrThrow(SpellPart.REGISTRY_KEY);
        for (SpellNode node : spell.root().children()) {
            if (!deliveredUnaimed(node, parts) || !noAimedEffects(node, parts)) {
                return false;
            }
        }
        return true;
    }

    private static boolean deliveredUnaimed(SpellNode node, net.minecraft.core.Registry<SpellPart> parts) {
        Holder<SpellPart> holder = parts.getHolder(node.part()).orElse(null);
        if (holder == null) {
            return false;
        }
        SpellPartKind kind = holder.value().kind();
        if (kind == SpellPartKind.DELIVERY) {
            return holder.is(TAG);
        }
        if (kind == SpellPartKind.EFFECT) {
            return true;
        }
        if (node.children().isEmpty()) {
            return false;
        }
        for (SpellNode child : node.children()) {
            if (!deliveredUnaimed(child, parts)) {
                return false;
            }
        }
        return true;
    }

    private static boolean noAimedEffects(SpellNode node, net.minecraft.core.Registry<SpellPart> parts) {
        Holder<SpellPart> holder = parts.getHolder(node.part()).orElse(null);
        if (holder == null || (holder.value().kind() == SpellPartKind.EFFECT && holder.is(AIMED_EFFECTS))) {
            return false;
        }
        for (SpellNode child : node.children()) {
            if (!noAimedEffects(child, parts)) {
                return false;
            }
        }
        return true;
    }
}
