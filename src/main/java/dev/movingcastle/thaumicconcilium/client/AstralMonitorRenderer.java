/**
 * The Astral Monitor (original: {@code AstralMonitorRenderer}). The body is Thaumaturge's scanner mesh, referenced by a
 * model of ours ({@code models/item/astral_monitor_frame.json}) that swaps in the original's frame texture; the
 * original used Thaumcraft's scanner OBJ. On top of it:
 * <ul>
 *   <li>the screen, a hexagon in the scanner's opening showing the End portal sky (the original's shader; here a
 *   flat generated star field);</li>
 *   <li>in first person, while the watched player is in the world, their health, blood, mana and runic shielding as
 *   constellation glyphs hovering over the screen, from the stats the server wrote into the item.</li>
 * </ul>
 */
public final class AstralMonitorRenderer extends BlockEntityWithoutLevelRenderer {
    public static final ModelResourceLocation FRAME = ModelResourceLocation.standalone(ThaumicConcilium.id("item/astral_monitor_frame"));
    private static final ResourceLocation SCREEN = ThaumicConcilium.id("textures/item/astral_screen.png");
    private static final ResourceLocation CONSTELLATIONS = LithographHud.CONSTELLATIONS;
    private static final int FULL_BRIGHT = 0xF000F0;
    /** The scanner body's top is at y 0.1 and its opening is a hexagon of radius 1 (original screen.obj). */
    /**
     * The opening's corners lie on the mesh's x axis (radius 1, flat edges at z +-0.866), and its top ring is at y 0.1.
     * The star field is a hexagon of the same orientation, larger than the opening and just below the ring, so the frame
     * itself masks the edge (a screen turned 30 degrees, or flush with the ring, shows notches and z-fighting).
     */
    private static final float SCREEN_Y = 0.09F;
    private static final float R = 1.1F;
    private static final float[][] HEXAGON = {{R, 0.0F}, {0.5F * R, 0.866F * R}, {-0.5F * R, 0.866F * R}, {-R, 0.0F}, {-0.5F * R, -0.866F * R}, {0.5F * R, -0.866F * R}};

    /**
     * The original's frame shader (atsral_frame.frag) painted each gem's body texels one flat colour,
     * mix(colours[index], colours[next], progress / 60) / 1.2 (alpha too), a fresh random next colour per gem every 60
     * renders. Here the fade is 20 ticks of game time, shared by all six gems, and the colours come from a hash of
     * (gem, cycle): no state. Even cycles pick white, red or green, odd ones grey, cyan or yellow, so a gem always changes.
     */
    private static final float[][] GEM_COLOURS = {{1.0F, 0.988F, 1.0F}, {0.42F, 0.42F, 0.42F}, {1.0F, 0.0F, 0.0F},
            {0.188F, 0.98F, 0.973F}, {0.188F, 1.0F, 0.0F}, {0.965F, 1.0F, 0.0F}};
    private static final float GEM_CYCLE_TICKS = 20.0F;
    /** Six 9x9 gem sprites in a row (generated by gen_phase6b_data.py): the body in white, and the untinted trim. */
    private static final ResourceLocation GEM_BODY = ThaumicConcilium.id("textures/item/astral_gems_body.png");
    private static final ResourceLocation GEM_TRIM = ThaumicConcilium.id("textures/item/astral_gems_trim.png");
    /** Each gem's box centre in the frame texture, from the generator. */
    private static final ResourceLocation GEM_DATA = ThaumicConcilium.id("astral_gems.json");
    /** How far the gem quads stand off the frame surface, in mesh units, against z-fighting. */
    private static final float GEM_LIFT = 0.002F;
    /**
     * The monitor's own right and up in the frame plane (mesh axes): right runs along the hexagon edge that is the flat
     * top edge in the held pose (the mesh's corners lie on x, so the edges run at 60 degrees to x), up is perpendicular
     * to it in the plane. Signs fixed against the render: with the opposite signs the sprites came out turned 180 degrees
     * (the texture's v runs the other way on this mesh), so these are the held pose's screen left and down in mesh terms.
     */
    private static final float[] MONITOR_RIGHT = {0.5F, 0.0F, -0.8660254F};
    private static final float[] MONITOR_UP = {-0.8660254F, 0.0F, -0.5F};

    /**
     * One gem socket on the frame mesh, found once: the centre (render pose, so minus 0.5, lifted off the surface), the
     * surface normal, the monitor's right and up projected into the surface, and the world size of one texel.
     */
    private record Gem(float[] centre, float[] normal, float[] right, float[] up, float texel) {}

    /** The model the gems were found on; rebuilt when a resource reload bakes a new one. */
    private BakedModel gemsModel;
    private Gem[] gems = new Gem[0];
    private int gemCell = 9;

    /** Set by {@link FirstPersonHands} while it draws the monitor itself (the item context is not first person then). */
    static boolean forceFirstPerson;

    private static AstralMonitorRenderer instance;

    private AstralMonitorRenderer() {
        super(Minecraft.getInstance().getBlockEntityRenderDispatcher(), Minecraft.getInstance().getEntityModels());
    }

    public static AstralMonitorRenderer get() {
        if (instance == null) {
            instance = new AstralMonitorRenderer();
        }
        return instance;
    }

    /** Client hook that gives the item this renderer. */
    public static final class Extensions implements IClientItemExtensions {
        @Override
        public BlockEntityWithoutLevelRenderer getCustomRenderer() {
            return AstralMonitorRenderer.get();
        }
    }

    @Override
    public void renderByItem(ItemStack stack, ItemDisplayContext context, PoseStack pose, MultiBufferSource buffers, int light, int overlay) {
        Minecraft mc = Minecraft.getInstance();
        BakedModel frame = mc.getModelManager().getModel(FRAME);
        pose.pushPose();
        // The item renderer has moved the origin to the model's corner; the scanner mesh is baked around the middle of
        // that cube, and the nested render below moves it back by half again, so go to the middle first.
        pose.translate(0.5F, 0.5F, 0.5F);
        mc.getItemRenderer().render(stack, context, false, pose, buffers, light, overlay, frame);
        this.drawScreen(pose, buffers.getBuffer(RenderType.entityCutoutNoCull(SCREEN)));
        this.drawGems(pose, buffers, mc, frame);
        if ((context.firstPerson() || forceFirstPerson) && mc.level != null) {
            this.drawGlyphs(stack, pose, buffers, mc);
        }
        pose.popPose();
    }

    private void drawScreen(PoseStack pose, VertexConsumer out) {
        PoseStack.Pose last = pose.last();
        int tint = 0xFFFFFFFF;
        float[] c = {0.0F, 0.0F};
        for (int i = 0; i < 6; i += 2) {
            float[] a = HEXAGON[i];
            float[] b = HEXAGON[(i + 1) % 6];
            float[] d = HEXAGON[(i + 2) % 6];
            vertex(out, last, c, tint);
            vertex(out, last, a, tint);
            vertex(out, last, b, tint);
            vertex(out, last, d, tint);
        }
    }

    private static int gemColour(long cycle, int gem) {
        long h = (cycle * 6 + gem + 1) * 0x9E3779B97F4A7C15L;
        h ^= h >>> 29;
        h *= 0xBF58476D1CE4E5B9L;
        h ^= h >>> 32;
        return (int) Math.floorMod(h, 3L) * 2 + (int) (cycle & 1L);
    }

    private void drawGems(PoseStack pose, MultiBufferSource buffers, Minecraft mc, BakedModel frame) {
        if (frame != this.gemsModel) {
            this.gems = findGems(mc, frame);
            this.gemsModel = frame;
        }
        if (this.gems.length == 0) {
            return;
        }
        float t = (mc.level == null ? 0L : mc.level.getGameTime()) + mc.getTimer().getGameTimeDeltaPartialTick(false);
        long cycle = (long) Math.floor(t / GEM_CYCLE_TICKS);
        float f = t / GEM_CYCLE_TICKS - cycle;
        PoseStack.Pose last = pose.last();
        VertexConsumer body = buffers.getBuffer(RenderType.entityTranslucent(GEM_BODY));
        for (int g = 0; g < this.gems.length; g++) {
            int from = gemColour(cycle, g);
            int to = gemColour(cycle + 1, g);
            int rgb = Math.round(255.0F / 1.2F) << 24;
            for (int c = 0; c < 3; c++) {
                float v = Mth.lerp(f, GEM_COLOURS[from][c], GEM_COLOURS[to][c]) / 1.2F;
                rgb |= Math.min(255, Math.round(v * 255.0F)) << (16 - 8 * c);
            }
            quad(body, last, this.gems[g], g, rgb);
        }
        VertexConsumer trim = buffers.getBuffer(RenderType.entityCutoutNoCull(GEM_TRIM));
        for (int g = 0; g < this.gems.length; g++) {
            quad(trim, last, this.gems[g], g, 0xFFFFFFFF);
        }
    }

    /** One upright gem sprite cell: edges along the monitor's right and up, one texel of world size per sprite texel. */
    private void quad(VertexConsumer out, PoseStack.Pose last, Gem gem, int index, int argb) {
        float half = this.gemCell * gem.texel * 0.5F;
        float u0 = index / 6.0F;
        float u1 = (index + 1) / 6.0F;
        float[][] sign = {{-1, 1, u0, 0.0F}, {-1, -1, u0, 1.0F}, {1, -1, u1, 1.0F}, {1, 1, u1, 0.0F}};
        for (float[] s : sign) {
            float x = gem.centre[0] + (s[0] * gem.right[0] + s[1] * gem.up[0]) * half;
            float y = gem.centre[1] + (s[0] * gem.right[1] + s[1] * gem.up[1]) * half;
            float z = gem.centre[2] + (s[0] * gem.right[2] + s[1] * gem.up[2]) * half;
            out.addVertex(last, x, y, z).setColor(argb).setUv(s[2], s[3]).setOverlay(OverlayTexture.NO_OVERLAY)
                    .setLight(FULL_BRIGHT).setNormal(last, gem.normal[0], gem.normal[1], gem.normal[2]);
        }
    }

    /** A flat piece of the frame mesh: its texture-to-position map and outward normal. */
    private record Face(float[][] uv, float[] a, float[] b, float[] c, float[] pa, float[] pb, float[] pc, float det, float[] normal) {}

    /** Texture position (pixels) to mesh position on a face's plane. */
    private static float[] place(Face face, float u, float v) {
        float du = u - face.a[0];
        float dv = v - face.a[1];
        float s = (du * (face.c[1] - face.a[1]) - (face.c[0] - face.a[0]) * dv) / face.det;
        float r = ((face.b[0] - face.a[0]) * dv - du * (face.b[1] - face.a[1])) / face.det;
        float[] p = new float[3];
        for (int k = 0; k < 3; k++) {
            p[k] = face.pa[k] + s * (face.pb[k] - face.pa[k]) + r * (face.pc[k] - face.pa[k]);
        }
        return p;
    }

    private static float dist(float[] a, float[] b) {
        return Mth.sqrt((a[0] - b[0]) * (a[0] - b[0]) + (a[1] - b[1]) * (a[1] - b[1]) + (a[2] - b[2]) * (a[2] - b[2]));
    }

    /** The axis projected into the plane with the given normal, normalised. */
    private static float[] inPlane(float[] axis, float[] n) {
        float d = axis[0] * n[0] + axis[1] * n[1] + axis[2] * n[2];
        float[] p = {axis[0] - d * n[0], axis[1] - d * n[1], axis[2] - d * n[2]};
        float len = Mth.sqrt(p[0] * p[0] + p[1] * p[1] + p[2] * p[2]);
        return new float[]{p[0] / len, p[1] / len, p[2] / len};
    }

    /**
     * Finds each gem's socket on the frame mesh. The generator's astral_gems.json holds the centre of each gem's box in
     * the frame texture; that point picks the mesh face whose UV polygon holds it (the one facing most upwards when
     * several share it) and that face's affine texture-to-position map gives the socket centre and the world size of one
     * texel there. Runs once per baked model.
     */
    private Gem[] findGems(Minecraft mc, BakedModel frame) {
        float[][] centres;
        int size;
        try (java.io.Reader in = new java.io.InputStreamReader(mc.getResourceManager().getResourceOrThrow(GEM_DATA).open(), java.nio.charset.StandardCharsets.UTF_8)) {
            com.google.gson.JsonObject json = com.google.gson.JsonParser.parseReader(in).getAsJsonObject();
            size = json.get("texture_size").getAsInt();
            this.gemCell = json.get("cell").getAsInt();
            com.google.gson.JsonArray arr = json.getAsJsonArray("centres");
            centres = new float[arr.size()][2];
            for (int i = 0; i < arr.size(); i++) {
                centres[i][0] = arr.get(i).getAsJsonArray().get(0).getAsFloat();
                centres[i][1] = arr.get(i).getAsJsonArray().get(1).getAsFloat();
            }
        } catch (java.io.IOException | RuntimeException e) {
            ThaumicConcilium.LOG.warn("Astral Monitor: gem data unreadable, no gems", e);
            return new Gem[0];
        }
        java.util.List<Face> faces = new java.util.ArrayList<>();
        RandomSource rand = RandomSource.create(42L);
        for (Direction d : new Direction[]{null, Direction.UP, Direction.DOWN, Direction.NORTH, Direction.SOUTH, Direction.EAST, Direction.WEST}) {
            for (BakedQuad q : frame.getQuads(null, d, rand, ModelData.EMPTY, null)) {
                Face face = face(q, size);
                if (face != null) {
                    faces.add(face);
                }
            }
        }
        java.util.List<Gem> out = new java.util.ArrayList<>();
        for (float[] centre : centres) {
            Face best = null;
            for (Face face : faces) {
                if (inside(face.uv, centre) && (best == null || face.normal[1] > best.normal[1])) {
                    best = face;
                }
            }
            if (best == null) {
                ThaumicConcilium.LOG.warn("Astral Monitor: a gem socket is not on the frame mesh");
                continue;
            }
            float[] p = place(best, centre[0], centre[1]);
            float texel = Mth.sqrt(dist(p, place(best, centre[0] + 1, centre[1])) * dist(p, place(best, centre[0], centre[1] + 1)));
            float[] c = new float[3];
            for (int k = 0; k < 3; k++) {
                c[k] = p[k] - 0.5F + best.normal[k] * GEM_LIFT;
            }
            out.add(new Gem(c, best.normal, inPlane(MONITOR_RIGHT, best.normal), inPlane(MONITOR_UP, best.normal), texel));
        }
        return out.toArray(new Gem[0]);
    }

    /** One baked quad (or triangle: the fourth vertex repeats the third) as a {@link Face}, UVs in texture pixels. */
    private static Face face(BakedQuad q, int size) {
        int[] v = q.getVertices();
        TextureAtlasSprite sprite = q.getSprite();
        float[][] p = new float[4][3];
        float[][] uv = new float[4][2];
        for (int i = 0; i < 4; i++) {
            p[i][0] = Float.intBitsToFloat(v[i * 8]);
            p[i][1] = Float.intBitsToFloat(v[i * 8 + 1]);
            p[i][2] = Float.intBitsToFloat(v[i * 8 + 2]);
            uv[i][0] = (Float.intBitsToFloat(v[i * 8 + 4]) - sprite.getU0()) / (sprite.getU1() - sprite.getU0()) * size;
            uv[i][1] = (Float.intBitsToFloat(v[i * 8 + 5]) - sprite.getV0()) / (sprite.getV1() - sprite.getV0()) * size;
        }
        // The triangle of three vertices with the widest UV area carries the affine map.
        int bi = -1;
        float bestArea = 0.01F;
        for (int skip = 0; skip < 4; skip++) {
            float area = Math.abs(cross(uv[(skip + 1) % 4], uv[(skip + 2) % 4], uv[(skip + 3) % 4]));
            if (area > bestArea) {
                bestArea = area;
                bi = skip;
            }
        }
        if (bi < 0) {
            return null;
        }
        float[] a = uv[(bi + 1) % 4];
        float[] b = uv[(bi + 2) % 4];
        float[] c = uv[(bi + 3) % 4];
        float[] pa = p[(bi + 1) % 4];
        float[] pb = p[(bi + 2) % 4];
        float[] pc = p[(bi + 3) % 4];
        float[] e1 = {pb[0] - pa[0], pb[1] - pa[1], pb[2] - pa[2]};
        float[] e2 = {pc[0] - pa[0], pc[1] - pa[1], pc[2] - pa[2]};
        float[] n = {e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]};
        float len = Mth.sqrt(n[0] * n[0] + n[1] * n[1] + n[2] * n[2]);
        if (len < 1.0E-8F) {
            return null;
        }
        // Outward side from the quad's declared face direction, not the winding.
        Direction dir = q.getDirection();
        float sign = Math.signum(n[0] * dir.getStepX() + n[1] * dir.getStepY() + n[2] * dir.getStepZ());
        if (sign == 0.0F) {
            sign = 1.0F;
        }
        for (int i = 0; i < 3; i++) {
            n[i] = n[i] / len * sign;
        }
        float det = (b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]);
        return new Face(uv, a, b, c, pa, pb, pc, det, n);
    }

    private static float cross(float[] a, float[] b, float[] c) {
        return (b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1]);
    }

    /** Point in the convex UV polygon (either winding; a triangle's repeated vertex is a zero-length edge). */
    private static boolean inside(float[][] poly, float[] pt) {
        boolean pos = false;
        boolean neg = false;
        for (int i = 0; i < 4; i++) {
            float[] a = poly[i];
            float[] b = poly[(i + 1) % 4];
            if (Math.abs(b[0] - a[0]) + Math.abs(b[1] - a[1]) < 1.0E-3F) {
                continue;
            }
            float cr = (b[0] - a[0]) * (pt[1] - a[1]) - (b[1] - a[1]) * (pt[0] - a[0]);
            if (cr > 1.0E-3F) {
                pos = true;
            }
            if (cr < -1.0E-3F) {
                neg = true;
            }
        }
        return !(pos && neg);
    }

    private static void vertex(VertexConsumer out, PoseStack.Pose last, float[] p, int argb) {
        out.addVertex(last, p[0], SCREEN_Y, p[1]).setColor(argb).setUv(p[0] / R * 0.5F + 0.5F, p[1] / R * 0.5F + 0.5F)
                .setOverlay(OverlayTexture.NO_OVERLAY).setLight(FULL_BRIGHT).setNormal(last, 0.0F, 1.0F, 0.0F);
    }

    private void drawGlyphs(ItemStack stack, PoseStack pose, MultiBufferSource buffers, Minecraft mc) {
        Optional<UUID> target = AstralMonitor.target(stack);
        PartyStats stats = stack.get(TCDataComponents.MONITOR_STATS.get());
        if (target.isEmpty() || stats == null || !stats.present() || mc.level.getPlayerByUUID(target.get()) == null) {
            return;
        }
        VertexConsumer out = buffers.getBuffer(RenderType.entityTranslucent(CONSTELLATIONS));
        pose.pushPose();
        // Original: rotate 90 about X, then 90 about Z, step half a unit back, and draw 0.02 scale sprites at z -0.1,
        // which leaves them floating just over half a unit above the scanner's centre.
        pose.mulPose(Axis.XP.rotationDegrees(90.0F));
        pose.mulPose(Axis.ZP.rotationDegrees(90.0F));
        pose.translate(0.0F, 0.0F, -0.5F);
        pose.scale(0.02F, 0.02F, 0.02F);
        sprite(out, pose, -32, -16, 48, stats.health());
        sprite(out, pose, -10, 5, 32, stats.blood());
        sprite(out, pose, 0, -24, 16, stats.mana());
        sprite(out, pose, 16, 0, 0, stats.runes());
        pose.popPose();
    }

    /** One 16 pixel frame of the sprite sheet (original: UtilsFX.drawTexturedQuad at z -0.1). */
    private static void sprite(VertexConsumer out, PoseStack pose, int x, int y, int u, int frame) {
        if (frame < 0) {
            return;
        }
        PoseStack.Pose last = pose.last();
        float v = 16.0F * frame;
        float u0 = u / 256.0F;
        float u1 = (u + 16) / 256.0F;
        float v0 = v / 256.0F;
        float v1 = (v + 16) / 256.0F;
        float z = -0.1F;
        corner(out, last, x, y + 16, z, u0, v1);
        corner(out, last, x + 16, y + 16, z, u1, v1);
        corner(out, last, x + 16, y, z, u1, v0);
        corner(out, last, x, y, z, u0, v0);
    }

    private static void corner(VertexConsumer out, PoseStack.Pose last, float x, float y, float z, float u, float v) {
        out.addVertex(last, x, y, z).setColor(0xFFFFFFFF).setUv(u, v).setOverlay(OverlayTexture.NO_OVERLAY)
                .setLight(FULL_BRIGHT).setNormal(last, 0.0F, 0.0F, 1.0F);
    }
}
