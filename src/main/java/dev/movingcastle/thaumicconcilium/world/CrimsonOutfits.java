package dev.movingcastle.thaumicconcilium.world;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.movingcastle.thaumicconcilium.ThaumicConcilium;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.SimpleJsonResourceReloadListener;
import net.minecraft.util.GsonHelper;
import net.minecraft.util.profiling.ProfilerFiller;
import net.minecraft.util.RandomSource;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.AddReloadListenerEvent;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * The worn outfits of our crimson cult mobs (data {@code thaumicconcilium:crimson_outfits/<entity path>.json}, generated by
 * {@code tools/gen_crimson_outfits.py}): a weighted list of {@code {source, weight, head, chest, legs, feet}}. Items that do not
 * exist are skipped with one log line per table; an outfit with no resolvable piece is dropped. Applied at finalizeSpawn by
 * {@link dev.movingcastle.thaumicconcilium.entity.mob.CrimsonCultist}; the host's own cultists never come through here.
 * Armour drop chance stays the host cultist's 0.05 per slot (set in its constructor; setItemSlot leaves it).
 */
@EventBusSubscriber(modid = ThaumicConcilium.MODID)
public final class CrimsonOutfits extends SimpleJsonResourceReloadListener {
    private static final Logger LOG = LoggerFactory.getLogger("thaumicconcilium/outfits");
    private static final Gson GSON = new GsonBuilder().create();
    private static final EquipmentSlot[] SLOTS = {EquipmentSlot.HEAD, EquipmentSlot.CHEST, EquipmentSlot.LEGS, EquipmentSlot.FEET};
    private static final String[] KEYS = {"head", "chest", "legs", "feet"};
    private static volatile Map<String, List<Outfit>> tables = Map.of();

    /** One outfit: its source ({@code host} or {@code armor_series}), its weight, and the item per slot (null = bare). */
    public record Outfit(String source, int weight, Item[] pieces) {
    }

    public CrimsonOutfits() {
        super(GSON, "crimson_outfits");
    }

    @SubscribeEvent
    public static void register(AddReloadListenerEvent event) {
        event.addListener(new CrimsonOutfits());
    }

    @Override
    protected void apply(Map<ResourceLocation, JsonElement> files, ResourceManager manager, ProfilerFiller profiler) {
        Map<String, List<Outfit>> out = new HashMap<>();
        for (var e : files.entrySet()) {
            if (!e.getKey().getNamespace().equals(ThaumicConcilium.MODID) || !e.getValue().isJsonObject()) {
                continue;
            }
            List<String> missing = new ArrayList<>();
            List<Outfit> list = new ArrayList<>();
            for (JsonElement el : GsonHelper.getAsJsonArray(e.getValue().getAsJsonObject(), "outfits")) {
                JsonObject o = el.getAsJsonObject();
                Item[] pieces = new Item[4];
                boolean any = false;
                for (int i = 0; i < 4; i++) {
                    String id = GsonHelper.getAsString(o, KEYS[i], "");
                    if (id.isEmpty()) {
                        continue;
                    }
                    ResourceLocation rl = ResourceLocation.tryParse(id);
                    Item item = rl == null ? null : BuiltInRegistries.ITEM.getOptional(rl).orElse(null);
                    if (item == null) {
                        missing.add(id);
                    } else {
                        pieces[i] = item;
                        any = true;
                    }
                }
                if (any) {
                    list.add(new Outfit(GsonHelper.getAsString(o, "source", "host"), Math.max(1, GsonHelper.getAsInt(o, "weight", 1)), pieces));
                }
            }
            if (!missing.isEmpty()) {
                LOG.warn("Crimson outfit table {}: skipped unknown items {}", e.getKey().getPath(), missing);
            }
            out.put(e.getKey().getPath(), List.copyOf(list));
        }
        tables = Map.copyOf(out);
    }

    /** The loaded table for an entity path (empty when there is none). */
    public static List<Outfit> table(String name) {
        return tables.getOrDefault(name, List.of());
    }

    /** Picks an outfit by weight; null when the table is empty. */
    public static Outfit pick(String name, RandomSource random) {
        List<Outfit> list = table(name);
        int total = 0;
        for (Outfit o : list) {
            total += o.weight();
        }
        if (total <= 0) {
            return null;
        }
        int roll = random.nextInt(total);
        for (Outfit o : list) {
            roll -= o.weight();
            if (roll < 0) {
                return o;
            }
        }
        return list.get(list.size() - 1);
    }

    /** Dresses the mob in a weighted outfit from its table (all four slots; missing pieces leave the slot bare). */
    public static Outfit dress(Mob mob, String name) {
        Outfit outfit = pick(name, mob.getRandom());
        if (outfit == null) {
            return null;
        }
        for (int i = 0; i < 4; i++) {
            mob.setItemSlot(SLOTS[i], outfit.pieces()[i] == null ? ItemStack.EMPTY : new ItemStack(outfit.pieces()[i]));
        }
        return outfit;
    }
}
