"""Converts the original's PontifexRobeModel (1.7.10 ModelRenderer constructor, WTFPL) into a 1.21 LayerDefinition.

Reads reference/src/ThaumicConcilium-1.1.1/.../client/render/model/PontifexRobeModel.java and writes
src/main/java/dev/movingcastle/thaumicconcilium/client/PontifexRobeModelData.java (static `create()` building the mesh).
Run once from the module root: python -I tools/convert_pontifex_model.py. The output is committed; this script only documents how it was made.
Boxes of the original are created with mirror = false (the flag is set after addBox), so none is mirrored.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', '..', 'reference', 'src', 'ThaumicConcilium-1.1.1', 'com', 'ilya3point999k', 'thaumicconcilium',
                   'client', 'render', 'model', 'PontifexRobeModel.java')
OUT = os.path.join(ROOT, 'src', 'main', 'java', 'dev', 'movingcastle', 'thaumicconcilium', 'client', 'PontifexRobeModelData.java')

PARENTS = {'field_78116_c': 'head', 'field_78115_e': 'body', 'field_78112_f': 'right_arm', 'field_78113_g': 'left_arm',
           'field_78123_h': 'right_leg', 'field_78124_i': 'left_leg'}

text = open(SRC, encoding='utf-8').read()
body = text[text.index('public PontifexRobeModel()'):text.index('public void func_78088_a')]
env = {}
for m in re.finditer(r'float (\w+) = (-?[\d.]+)F;', body):
    env[m.group(1)] = float(m.group(2))


def ev(expr):
    expr = expr.strip()
    expr = re.sub(r'\(float\)\s*', '', expr)
    expr = re.sub(r'(\d)F\b', r'\1', expr)
    expr = expr.replace('Math.PI', 'math.pi')
    return float(eval(expr, {'math': math}, dict(env)))


parts = {}   # name -> dict(u, v, box, pivot, rot)
groups = {}  # group name -> parent name (head/body/... or another group)
children = {}  # name -> parent


def get(name):
    return parts.setdefault(name, {'u': 0, 'v': 0, 'box': None, 'pivot': (0.0, 0.0, 0.0), 'rot': (0.0, 0.0, 0.0)})


for m in re.finditer(r'this\.(\w+) = new ModelRenderer\(this, (\d+), (\d+)\);', body):
    p = get(m.group(1))
    p['u'], p['v'] = int(m.group(2)), int(m.group(3))
for m in re.finditer(r'this\.(\w+)\.func_78789_a\((.*?)\);', body):
    a = [ev(x) for x in re.split(r',(?![^(]*\))', m.group(2))]
    get(m.group(1))['box'] = a
for m in re.finditer(r'this\.(\w+)\.func_78793_a\((.*?)\);', body):
    get(m.group(1))['pivot'] = tuple(ev(x) for x in m.group(2).split(','))
for m in re.finditer(r'this\.setRotation\(this\.(\w+), (.*?)\);', body):
    parts[m.group(1)]['rot'] = tuple(ev(x) for x in m.group(2).split(','))
for m in re.finditer(r'this\.(\w+)\.func_78792_a\(this\.(\w+)\);', body):
    children[m.group(2)] = PARENTS.get(m.group(1), m.group(1))

# Every part that is not a root limb and not a child of something is dropped (the base biped's own parts have no cubes).
named = [n for n in parts if n in children]
lines = []


def f(x):
    return repr(round(x, 5)) + 'F' if x == x else '0F'


def emit(name, parent_var, indent):
    p = parts[name]
    var = 'p_' + name
    if p['box']:
        x, y, z, w, h, d = p['box']
        cubes = f'CubeListBuilder.create().texOffs({p["u"]}, {p["v"]}).addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)})'
    else:
        cubes = 'CubeListBuilder.create()'
    px, py, pz = p['pivot']
    rx, ry, rz = p['rot']
    pose = f'PartPose.offsetAndRotation({f(px)}, {f(py)}, {f(pz)}, {f(rx)}, {f(ry)}, {f(rz)})'
    lines.append(f'{indent}PartDefinition {var} = {parent_var}.addOrReplaceChild("{name}", {cubes}, {pose});')
    return var


# groups first (they are parents), then leaves, in dependency order
order = []
seen = set()


def visit(n):
    if n in seen:
        return
    par = children[n]
    if par in children:
        visit(par)
    seen.add(n)
    order.append(n)


for n in named:
    visit(n)

vars_ = {'head': 'head', 'body': 'body', 'right_arm': 'right_arm', 'left_arm': 'left_arm', 'right_leg': 'right_leg', 'left_leg': 'left_leg'}
for n in order:
    par = children[n]
    vars_[n] = emit(n, vars_[par], '        ')

java = '''package dev.movingcastle.thaumicconcilium.client;

import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.model.geom.PartPose;

/**
 * The Pontifex's robe mesh (GENERATED by tools/convert_pontifex_model.py from the original's PontifexRobeModel, WTFPL: the same boxes,
 * pivots and rotations on a 128x64 texture). Hung on the vanilla biped skeleton: head, body, both arms, both legs; the groups
 * {@code cloth} and {@code armor} (body) and {@code leftBoot} and {@code rightBoot} (legs) are switched per slot by {@link PontifexRobeModel}.
 */
final class PontifexRobeModelData {
    private PontifexRobeModelData() {
    }

    static LayerDefinition create() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition head = root.addOrReplaceChild("head", CubeListBuilder.create(), PartPose.ZERO);
        root.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.ZERO);
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create(), PartPose.ZERO);
        PartDefinition right_arm = root.addOrReplaceChild("right_arm", CubeListBuilder.create(), PartPose.offset(-5.0F, 2.0F, 0.0F));
        PartDefinition left_arm = root.addOrReplaceChild("left_arm", CubeListBuilder.create(), PartPose.offset(5.0F, 2.0F, 0.0F));
        PartDefinition right_leg = root.addOrReplaceChild("right_leg", CubeListBuilder.create(), PartPose.offset(-1.9F, 12.0F, 0.0F));
        PartDefinition left_leg = root.addOrReplaceChild("left_leg", CubeListBuilder.create(), PartPose.offset(1.9F, 12.0F, 0.0F));
''' + '\n'.join(lines) + '''
        return LayerDefinition.create(mesh, 128, 64);
    }
}
'''
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write(java)
print(f'{len(order)} parts written to {OUT}')
missing = [n for n in parts if n not in children and n not in ('Shape1H',) and parts[n]['box']]
print('boxed parts without a parent (dropped):', missing)
