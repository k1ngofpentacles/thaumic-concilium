"""Phase 5d cycle 2b: the Concilium Grove biome, its tags and its data maps. Run after gen_phase5d_data.py, before gen_lang.py.

The grove is written as a "subclass" of Thaumaturge's magical_forest: the same climate, effects, spawners and feature ids (facts and ids
only: no Thaumaturge code or art), joined to the same tags and data maps. The values below were read off Thaumaturge's own biome (a
throwaway pack-test dump of Biome.DIRECT_CODEC, 2026-11-22); the biome is never generated by worldgen (the painter writes it into
existing chunks), the feature list exists so placeWithBiomeCheck accepts the grove in cycle 2c.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from genlib import *

BIOME = f'{NS}:concilium_grove'
MAGICAL_FOREST = f'{T}:magical_forest'

# ---------------------------------------------------------------- the biome (magical_forest's values)
TEMPERATURE = 0.8
DOWNFALL = 0.4
EFFECTS = {'sky_color': 7907327, 'fog_color': 12638463, 'water_color': 30702, 'water_fog_color': 329011, 'grass_color': 5635969, 'foliage_color': 6750149}
def _s(t, weight, lo, hi):
    return {'type': t, 'weight': weight, 'minCount': lo, 'maxCount': hi}


# vanilla's farm animals and common spawns, then Thaumaturge's wolf, horse, witch, enderman, vex and wisp (the duplicates are its own)
SPAWNERS = {
    'monster': [_s('minecraft:spider', 100, 4, 4), _s('minecraft:zombie', 95, 4, 4), _s('minecraft:zombie_villager', 5, 1, 1),
                _s('minecraft:skeleton', 100, 4, 4), _s('minecraft:creeper', 100, 4, 4), _s('minecraft:slime', 100, 4, 4),
                _s('minecraft:enderman', 10, 1, 4), _s('minecraft:witch', 5, 1, 1), _s('minecraft:witch', 3, 1, 1),
                _s('minecraft:enderman', 3, 1, 1), _s('minecraft:vex', 1, 1, 1), _s(f'{T}:wisp', 20, 1, 2)],
    'creature': [_s('minecraft:sheep', 12, 4, 4), _s('minecraft:pig', 10, 4, 4), _s('minecraft:chicken', 10, 4, 4), _s('minecraft:cow', 8, 4, 4),
                 _s('minecraft:wolf', 2, 1, 3), _s('minecraft:horse', 2, 1, 3)],
    'ambient': [_s('minecraft:bat', 10, 8, 8)],
    'axolotls': [],
    'underground_water_creature': [_s('minecraft:glow_squid', 10, 4, 6)],
    'water_creature': [],
    'water_ambient': [],
    'misc': [],
}
SPAWN_COSTS = {}

features = [[] for _ in range(11)]
features[2] = ['minecraft:forest_rock']                                       # LOCAL_MODIFICATIONS
features[9] = [f'{T}:trees_magic_forest', f'{T}:magic_forest_flora', f'{T}:mana_pods', 'minecraft:patch_waterlily']  # VEGETAL_DECORATION
features[10] = [f'{T}:nodes_magical']                                         # TOP_LAYER_MODIFICATION

w(f'data/{NS}/worldgen/biome/concilium_grove.json', {
    'has_precipitation': True,
    'temperature': TEMPERATURE,
    'downfall': DOWNFALL,
    'effects': EFFECTS,
    'spawners': SPAWNERS,
    'spawn_costs': SPAWN_COSTS,
    'carvers': {},
    'features': features,
})

# ---------------------------------------------------------------- tags: the grove joins the same ones as magical_forest, plus our own
w(f'data/{NS}/tags/worldgen/biome/concilium_grove.json', {'values': [BIOME]})
w(f'data/{T}/tags/worldgen/biome/is_magical.json', {'values': [BIOME]})
w(f'data/{T}/tags/worldgen/biome/has_greatwood.json', {'values': [BIOME]})
w(f'data/{T}/tags/worldgen/biome/has_structure/mound.json', {'values': [BIOME]})
w('data/minecraft/tags/worldgen/biome/is_forest.json', {'values': [BIOME]})
w('data/minecraft/tags/worldgen/biome/is_overworld.json', {'values': [BIOME]})

# ---------------------------------------------------------------- data maps (entries merge by key with Thaumaturge's)
w(f'data/{T}/data_maps/worldgen/biome/aura_modifier.json', {'values': {BIOME: {'value': 0.625}}})
w(f'data/{T}/data_maps/worldgen/biome/biome_aspects.json', {'values': {BIOME: [f'{T}:ordo', f'{T}:terra']}})
print('grove biome, tags and data maps written')
